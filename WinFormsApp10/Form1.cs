    static class Gfx
    {
        public static GraphicsPath RoundRect(RectangleF r, float radius)
        {
            float d = radius * 2;
            var p = new GraphicsPath();
            p.AddArc(r.X, r.Y, d, d, 180, 90);
            p.AddArc(r.Right - d, r.Y, d, d, 270, 90);
            p.AddArc(r.Right - d, r.Bottom - d, d, d, 0, 90);
            p.AddArc(r.X, r.Bottom - d, d, d, 90, 90);
            p.CloseFigure();
            return p;
        }
    }

    // Full-page background: your photo (cover mode + dark tint), or a drawn sunset sky if no photo is found
    class SkyPanel : Panel
    {
        public Image Photo { get; set; }
        public float OverlayStrength { get; set; } = 1f;
        private Bitmap cache;
        private Size cacheSize;

        public SkyPanel()
        {
            SetStyle(ControlStyles.UserPaint | ControlStyles.AllPaintingInWmPaint |
                     ControlStyles.OptimizedDoubleBuffer | ControlStyles.ResizeRedraw, true);
        }

        protected override void Dispose(bool disposing)
        {
            if (disposing && cache != null) { cache.Dispose(); cache = null; }
            base.Dispose(disposing);
        }

        private int A(int alpha)
        {
            return Math.Max(0, Math.Min(255, (int)(alpha * OverlayStrength)));
        }

        private void BuildCache(Size size)
        {
            if (cache != null) cache.Dispose();
            cache = new Bitmap(size.Width, size.Height);
            cacheSize = size;

            using (var g = Graphics.FromImage(cache))
            {
                g.InterpolationMode = InterpolationMode.HighQualityBicubic;
                g.PixelOffsetMode = PixelOffsetMode.HighQuality;

                float scale = Math.Max((float)size.Width / Photo.Width, (float)size.Height / Photo.Height);
                float w = Photo.Width * scale, h = Photo.Height * scale;
                g.DrawImage(Photo, (size.Width - w) / 2f, (size.Height - h) / 2f, w, h);

                // Dark blue tint: stronger at the top and bottom so white text stays readable
                var rect = new Rectangle(Point.Empty, size);
                using (var br = new LinearGradientBrush(rect, Color.Black, Color.Black, 90f))
                {
                    br.InterpolationColors = new ColorBlend
                    {
                        Positions = new[] { 0f, 0.5f, 1f },
                        Colors = new[]
                        {
                            Color.FromArgb(A(110), 8, 24, 56),
                            Color.FromArgb(A(35), 8, 24, 56),
                            Color.FromArgb(A(130), 8, 24, 56)
                        }
                    };
                    g.FillRectangle(br, rect);
                }
            }
        }

        protected override void OnPaint(PaintEventArgs e)
        {
            var g = e.Graphics;
            var rect = ClientRectangle;
            if (rect.Width < 2 || rect.Height < 2) return;

            if (Photo != null)
            {
                if (cache == null || cacheSize != rect.Size) BuildCache(rect.Size);
                g.DrawImageUnscaled(cache, 0, 0);
                return;
            }

            // ---- Fallback: drawn sunset sky ----
            g.SmoothingMode = SmoothingMode.AntiAlias;
            using (var br = new LinearGradientBrush(rect, Color.Black, Color.Black, 90f))
            {
                br.InterpolationColors = new ColorBlend
                {
                    Positions = new[] { 0f, 0.35f, 0.58f, 0.72f, 1f },
                    Colors = new[]
                    {
                        Color.FromArgb(84, 95, 118),
                        Color.FromArgb(150, 140, 150),
                        Color.FromArgb(238, 152, 74),
                        Color.FromArgb(92, 82, 96),
                        Color.FromArgb(44, 46, 64)
                    }
                };
                g.FillRectangle(br, rect);
            }

            var rnd = new Random(11);
            for (int i = 0; i < 28; i++)
            {
                float cw = rnd.Next(220, 520), ch = rnd.Next(50, 120);
                float x = rnd.Next(-100, rect.Width);
                float y = rect.Height * (0.70f + (float)rnd.NextDouble() * 0.32f);
                using (var b = new SolidBrush(Color.FromArgb(rnd.Next(45, 90), 58, 54, 74)))
                    g.FillEllipse(b, x, y, cw, ch);
            }
        }
    }

    // Rounded translucent "glass" panel
    class GlassPanel : Panel
    {
        public int Radius { get; set; } = 24;
        public Color Fill { get; set; } = Color.FromArgb(110, 30, 34, 50);
        public Color Border { get; set; } = Color.FromArgb(60, 255, 255, 255);

        public GlassPanel()
        {
            SetStyle(ControlStyles.UserPaint | ControlStyles.AllPaintingInWmPaint |
                     ControlStyles.OptimizedDoubleBuffer | ControlStyles.ResizeRedraw |
                     ControlStyles.SupportsTransparentBackColor, true);
            BackColor = Color.Transparent;
        }

        protected override void OnPaint(PaintEventArgs e)
        {
            base.OnPaint(e);
            e.Graphics.SmoothingMode = SmoothingMode.AntiAlias;
            var rect = new RectangleF(0.5f, 0.5f, Width - 2f, Height - 2f);
            using (var path = Gfx.RoundRect(rect, Radius))
            using (var fill = new SolidBrush(Fill))
            using (var pen = new Pen(Border, 1.2f))
            {
                e.Graphics.FillPath(fill, path);
                e.Graphics.DrawPath(pen, path);
            }
        }
    }

    // Pill-shaped button with an optional round icon on the right
    class PillButton : Control
    {
        public Color Fill { get; set; } = Color.White;
        public Color TextColor { get; set; } = Color.Black;
        public Color IconBack { get; set; } = Color.Black;
        public Color IconFore { get; set; } = Color.White;
        public string Glyph { get; set; } = "\u2708";
        public bool ShowIcon { get; set; } = true;
        private bool hover, down;

        public PillButton()
        {
            SetStyle(ControlStyles.UserPaint | ControlStyles.AllPaintingInWmPaint |
                     ControlStyles.OptimizedDoubleBuffer | ControlStyles.ResizeRedraw |
                     ControlStyles.SupportsTransparentBackColor, true);
            SetStyle(ControlStyles.Selectable, false);
            BackColor = Color.Transparent;
            Cursor = Cursors.Hand;
            Font = new Font("Segoe UI Semibold", 10.5F);
            Size = new Size(170, 46);
        }

        protected override void OnTextChanged(EventArgs e) { Invalidate(); base.OnTextChanged(e); }
        protected override void OnMouseEnter(EventArgs e) { hover = true; Invalidate(); base.OnMouseEnter(e); }
        protected override void OnMouseLeave(EventArgs e) { hover = false; down = false; Invalidate(); base.OnMouseLeave(e); }
        protected override void OnMouseDown(MouseEventArgs e) { down = true; Invalidate(); base.OnMouseDown(e); }
        protected override void OnMouseUp(MouseEventArgs e) { down = false; Invalidate(); base.OnMouseUp(e); }

        private static Color Shift(Color c, int amt)
        {
            int lum = (c.R * 299 + c.G * 587 + c.B * 114) / 1000;
            int d = lum > 170 ? -amt : amt;
            return Color.FromArgb(c.A,
                Math.Max(0, Math.Min(255, c.R + d)),
                Math.Max(0, Math.Min(255, c.G + d)),
                Math.Max(0, Math.Min(255, c.B + d)));
        }

        protected override void OnPaint(PaintEventArgs e)
        {
            var g = e.Graphics;
            g.SmoothingMode = SmoothingMode.AntiAlias;
            g.TextRenderingHint = System.Drawing.Text.TextRenderingHint.ClearTypeGridFit;

            var r = new RectangleF(0.5f, 0.5f, Width - 2f, Height - 2f);
            Color c = down ? Shift(Fill, 30) : hover ? Shift(Fill, 16) : Fill;
            using (var path = Gfx.RoundRect(r, r.Height / 2))
            using (var b = new SolidBrush(c))
                g.FillPath(b, path);

            float textRight = Width;
            if (ShowIcon)
            {
                float d = Height - 12;
                var ir = new RectangleF(Width - d - 6, (Height - d) / 2f, d, d);
                using (var b = new SolidBrush(IconBack)) g.FillEllipse(b, ir);
                using (var f = new Font("Segoe UI Symbol", 10.5F))
                using (var sf = new StringFormat { Alignment = StringAlignment.Center, LineAlignment = StringAlignment.Center })
                using (var b = new SolidBrush(IconFore))
                    g.DrawString(Glyph, f, b, ir, sf);
                textRight = ir.Left;
            }

            using (var sf = new StringFormat { Alignment = StringAlignment.Center, LineAlignment = StringAlignment.Center })
            using (var b = new SolidBrush(TextColor))
                g.DrawString(Text, Font, b, new RectangleF(0, 0, textRight, Height), sf);
        }
    }

    // The state of a seat. An enum instead of loose text ("Booked", "Available", ...):
    // the compiler checks the names, and a typo can no longer slip in.
    enum SeatStatus
    {
        Available,
        Booked,
        Selected
    }

    // The three screens of the app (used for navigation and the Back arrow)
    enum AppPage
    {
        Login,
        Home,
        Booking
    }

    // One place that decides which color belongs to which SeatStatus
    static class SeatPalette
    {
        public static Color Fill(SeatStatus status)
        {
            switch (status)
            {
                case SeatStatus.Booked: return Color.FromArgb(229, 57, 53);
                case SeatStatus.Selected: return Color.FromArgb(62, 66, 88);
                default: return Color.FromArgb(76, 175, 80);
            }
        }
    }

    // Seat color legend: draws one entry for every SeatStatus value
    class Legend : Control
    {
        public Legend()
        {
            SetStyle(ControlStyles.UserPaint | ControlStyles.AllPaintingInWmPaint |
                     ControlStyles.OptimizedDoubleBuffer | ControlStyles.ResizeRedraw |
                     ControlStyles.SupportsTransparentBackColor, true);
            BackColor = Color.Transparent;
            ForeColor = Color.White;
            Font = new Font("Segoe UI", 10F);
        }

        protected override void OnPaint(PaintEventArgs e)
        {
            var g = e.Graphics;
            g.SmoothingMode = SmoothingMode.AntiAlias;
            g.TextRenderingHint = System.Drawing.Text.TextRenderingHint.ClearTypeGridFit;

            // All values of the enum, in the order they are declared
            var statuses = (SeatStatus[])Enum.GetValues(typeof(SeatStatus));

            float total = 0;
            var widths = new float[statuses.Length];
            for (int i = 0; i < statuses.Length; i++)
            {
                widths[i] = 24 + g.MeasureString(statuses[i].ToString(), Font).Width;
                total += widths[i];
            }
            total += 28 * (statuses.Length - 1);

            float x = (Width - total) / 2f;
            float y = (Height - 18) / 2f;
            for (int i = 0; i < statuses.Length; i++)
            {
                using (var path = Gfx.RoundRect(new RectangleF(x, y, 18, 18), 4))
                using (var b = new SolidBrush(SeatPalette.Fill(statuses[i])))
                {
                    g.FillPath(b, path);
                    if (statuses[i] == SeatStatus.Selected)
                        using (var pen = new Pen(Color.FromArgb(33, 150, 243), 2.5f))
                            g.DrawPath(pen, path);
                }
                using (var tb = new SolidBrush(ForeColor))
                    g.DrawString(statuses[i].ToString(), Font, tb, x + 24, (Height - Font.Height) / 2f);
                x += widths[i] + 28;
            }
        }
    }

