        // =====================================================
        //  Flights + seats (UI only, no backend yet)
        // =====================================================
        private void LoadFlights(string from, string to)
        {
            var list = flights.Where(f => (from == "Any" || f.From == from) && (to == "Any" || f.To == to)).ToList();
            bool noMatch = list.Count == 0;
            if (noMatch) list = flights;

            loadingFlights = true;
            dgvFlights.Rows.Clear();
            foreach (var f in list)
                dgvFlights.Rows.Add(f.No, f.From, f.To, f.Time, "$" + f.Price);
            if (dgvFlights.Rows.Count > 0)
            {
                dgvFlights.ClearSelection();
                dgvFlights.Rows[0].Selected = true;
                dgvFlights.CurrentCell = dgvFlights.Rows[0].Cells[0];
            }
            loadingFlights = false;

            OnFlightChanged();
            if (noMatch) lblStatus.Text = "No flights on that route, showing all flights.";
        }

        private void OnFlightChanged()
        {
            if (dgvFlights.CurrentRow == null) return;
            var row = dgvFlights.CurrentRow;
            currentFlight = row.Cells["FlightNo"].Value.ToString();
            lblFlightTitle.Text = string.Format("{0}:  {1}  \u2192  {2}",
                currentFlight, row.Cells["From"].Value, row.Cells["To"].Value);
            BuildSeatGrid();
            lblSelectedSeat.Text = "Selected seat: none";
            lblStatus.Text = "Flight " + currentFlight + " selected. Choose a seat.";
        }

        private SeatStatus[,] GetSeatState(string flightNo)
        {
            SeatStatus[,] st;
            if (!seatStates.TryGetValue(flightNo, out st))
            {
                st = new SeatStatus[Rows, 6];   // every seat starts as Available
                for (int r = 0; r < Rows; r++)
                    for (int c = 0; c < 6; c++)
                        if (rng.Next(100) < 25) st[r, c] = SeatStatus.Booked;
                seatStates[flightNo] = st;
            }
            return st;
        }

        private void BuildSeatGrid()
        {
            seatGrid.SuspendLayout();
            while (seatGrid.Controls.Count > 0) seatGrid.Controls[0].Dispose();
            seatGrid.ColumnStyles.Clear();
            seatGrid.RowStyles.Clear();
            selectedSeat = null;

            // Columns: [row no] A B C [aisle] D E F
            seatGrid.ColumnCount = 8;
            seatGrid.RowCount = Rows + 1;
            seatGrid.ColumnStyles.Add(new ColumnStyle(SizeType.Absolute, 30));
            for (int i = 0; i < 3; i++) seatGrid.ColumnStyles.Add(new ColumnStyle(SizeType.Percent, 16.6f));
            seatGrid.ColumnStyles.Add(new ColumnStyle(SizeType.Absolute, 26));
            for (int i = 0; i < 3; i++) seatGrid.ColumnStyles.Add(new ColumnStyle(SizeType.Percent, 16.6f));
            seatGrid.RowStyles.Add(new RowStyle(SizeType.Absolute, 24));
            for (int r = 0; r < Rows; r++) seatGrid.RowStyles.Add(new RowStyle(SizeType.Percent, 100f / Rows));

            string[] letters = { "A", "B", "C", "D", "E", "F" };
            var dim = Color.FromArgb(180, 195, 220);

            for (int c = 0; c < 6; c++)
            {
                int gridCol = c < 3 ? c + 1 : c + 2;
                seatGrid.Controls.Add(new Label
                {
                    Text = letters[c],
                    Dock = DockStyle.Fill,
                    TextAlign = ContentAlignment.MiddleCenter,
                    ForeColor = dim,
                    BackColor = Color.Transparent,
                    Font = new Font("Segoe UI", 9F, FontStyle.Bold)
                }, gridCol, 0);
            }

            var state = GetSeatState(currentFlight);
            for (int r = 0; r < Rows; r++)
            {
                seatGrid.Controls.Add(new Label
                {
                    Text = (r + 1).ToString(),
                    Dock = DockStyle.Fill,
                    TextAlign = ContentAlignment.MiddleCenter,
                    ForeColor = dim,
                    BackColor = Color.Transparent
                }, 0, r + 1);

                for (int c = 0; c < 6; c++)
                {
                    int gridCol = c < 3 ? c + 1 : c + 2;
                    var seat = new Button
                    {
                        Text = (r + 1) + letters[c],
                        Dock = DockStyle.Fill,
                        Margin = new Padding(4),
                        FlatStyle = FlatStyle.Flat,
                        ForeColor = Color.White,
                        Font = new Font("Segoe UI", 9F, FontStyle.Bold),
                        Cursor = Cursors.Hand,
                        UseVisualStyleBackColor = false,
                        Tag = new Point(r, c)
                    };
                    seat.FlatAppearance.BorderSize = 2;
                    PaintSeat(seat, state[r, c], false);
                    seat.Click += Seat_Click;
                    seatGrid.Controls.Add(seat, gridCol, r + 1);
                }
            }
            seatGrid.ResumeLayout();
        }

        // status is Available or Booked; "selected" only adds the blue border
        private void PaintSeat(Button seat, SeatStatus status, bool selected)
        {
            seat.BackColor = SeatPalette.Fill(status);
            seat.FlatAppearance.BorderColor = selected ? SelectedBorder : seat.BackColor;
        }

        private SeatStatus GetStatus(Button seat)
        {
            var p = (Point)seat.Tag;
            return GetSeatState(currentFlight)[p.X, p.Y];
        }

        private void Seat_Click(object sender, EventArgs e)
        {
            var seat = (Button)sender;
            if (selectedSeat != null && selectedSeat != seat)
                PaintSeat(selectedSeat, GetStatus(selectedSeat), false);

            selectedSeat = seat;
            PaintSeat(seat, GetStatus(seat), true);
            lblSelectedSeat.Text = string.Format("Selected seat: {0} ({1})", seat.Text, GetStatus(seat));
        }

        private void BookSeat()
        {
            if (selectedSeat == null)
            {
                MessageBox.Show("Please select a seat first.", BrandName, MessageBoxButtons.OK, MessageBoxIcon.Information);
                return;
            }
            if (GetStatus(selectedSeat) == SeatStatus.Booked)
            {
                MessageBox.Show("Seat " + selectedSeat.Text + " is already booked.", BrandName, MessageBoxButtons.OK, MessageBoxIcon.Warning);
                return;
            }

            var p = (Point)selectedSeat.Tag;
            GetSeatState(currentFlight)[p.X, p.Y] = SeatStatus.Booked;
            PaintSeat(selectedSeat, SeatStatus.Booked, true);
            lblSelectedSeat.Text = string.Format("Selected seat: {0} ({1})", selectedSeat.Text, SeatStatus.Booked);
            lblStatus.Text = string.Format("Seat {0} booked successfully by {1}.", selectedSeat.Text, currentUser);
        }

        private void CancelSeat()
        {
            if (selectedSeat == null)
            {
                MessageBox.Show("Please select a seat first.", BrandName, MessageBoxButtons.OK, MessageBoxIcon.Information);
                return;
            }
            if (GetStatus(selectedSeat) != SeatStatus.Booked)
            {
                MessageBox.Show("Seat " + selectedSeat.Text + " is not booked.", BrandName, MessageBoxButtons.OK, MessageBoxIcon.Information);
                return;
            }

            var p = (Point)selectedSeat.Tag;
            GetSeatState(currentFlight)[p.X, p.Y] = SeatStatus.Available;
            PaintSeat(selectedSeat, SeatStatus.Available, true);
            lblSelectedSeat.Text = string.Format("Selected seat: {0} ({1})", selectedSeat.Text, SeatStatus.Available);
            lblStatus.Text = "Booking for seat " + selectedSeat.Text + " cancelled.";
        }

