        // Decodes the embedded Base64 JPEG (BgData) into an image
        private static Image LoadBackground()
        {
            try
            {
                byte[] bytes = Convert.FromBase64String(string.Concat(BgData));
                using (var ms = new MemoryStream(bytes))
                using (var img = Image.FromStream(ms))
                    return new Bitmap(img);
            }
            catch
            {
                return null;   // falls back to the drawn sky
            }
        }

