        // Shows a page. When remember is true, the page we leave is saved so the Back arrow can return to it.
        private void ShowPage(AppPage page, bool remember = true)
        {
            if (page == AppPage.Login)
                history.Clear();                       // a new session starts at the login screen
            else if (remember && page != currentPage)
                history.Push(currentPage);

            currentPage = page;
            var panel = PanelFor(page);
            pageLogin.Visible = panel == pageLogin;
            pageHome.Visible = panel == pageHome;
            pageBooking.Visible = panel == pageBooking;
            panel.BringToFront();
            LayoutAll();
            if (page == AppPage.Login) txtUser.Focus();
        }

        // The Back arrow: goes one step back to the previous page
        private void GoBack()
        {
            if (history.Count == 0) return;

            AppPage previous = history.Peek();
            if (previous == AppPage.Login)
            {
                // Going back from Home to Login means signing out, so ask first
                var answer = MessageBox.Show("Go back to the login screen? You will be signed out.", BrandName,
                    MessageBoxButtons.YesNo, MessageBoxIcon.Question);
                if (answer != DialogResult.Yes) return;
                currentUser = null;
                ShowPage(AppPage.Login, false);
                return;
            }

            history.Pop();
            ShowPage(previous, false);
        }

