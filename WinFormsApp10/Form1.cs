        private void AddHint(TextBox tb, string hint)
        {
            Color hintColor = Color.FromArgb(160, 168, 190);
            tb.Text = hint;
            tb.ForeColor = hintColor;
            tb.Enter += (s, e) =>
            {
                if (tb.ForeColor == hintColor) { tb.Text = ""; tb.ForeColor = Color.White; }
            };
            tb.Leave += (s, e) =>
            {
                if (tb.Text.Trim() == "") { tb.Text = hint; tb.ForeColor = hintColor; }
            };
        }

